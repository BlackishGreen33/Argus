export const messages: Record<Locale, MessageMap> = { "zh-CN": zhCN, "zh-TW": zhTW, en };

const LocaleContext = createContext<{
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, values?: TranslationValues) => string;
}>({
  locale: "zh-CN",
  setLocale: () => undefined,
  t: (key) => key,
});

function interpolate(value: string, values?: TranslationValues) {
  if (!values) return value;
  return Object.entries(values).reduce(
    (result, [key, replacement]) => result.replaceAll(`{{${key}}}`, String(replacement)),
    value,
  );
}

export const I18nProvider: React.FC<React.PropsWithChildren> = ({ children }) => {
  const [locale, setLocaleState] = useState<Locale>("zh-CN");
  const [localeHydrated, setLocaleHydrated] = useState(false);
  useEffect(() => {
    if (!localeHydrated) return;
    document.documentElement.lang = locale;
    window.localStorage.setItem(STORAGE_KEYS.locale, locale);
  }, [locale, localeHydrated]);
  useEffect(() => {
    const stored = window.localStorage.getItem(STORAGE_KEYS.locale);
    if (stored === "zh-CN" || stored === "zh-TW" || stored === "en") setLocaleState(stored);
    setLocaleHydrated(true);
  }, []);
  const setLocale = useCallback((next: Locale) => setLocaleState(next), []);
  const t = useCallback(
    (key: string, values?: TranslationValues) =>
      interpolate(messages[locale][key] ?? messages["zh-CN"][key] ?? key, values),
    [locale],
  );
  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
};

export function useI18n() {
  return useContext(LocaleContext);
}
